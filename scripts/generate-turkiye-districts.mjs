// `pnpm turkiye:districts`: regenerates lib/turkiye-districts.ts from turkey-neighbourhoods (PTT data, a 24 MB dev dependency).
import { writeFileSync } from "node:fs";
import { getCityCodes, getCityNames, getDistrictsByCityCode } from "turkey-neighbourhoods";

const codes = getCityCodes();
const names = getCityNames();
if (codes.length !== 81 || names.length !== 81) throw new Error("Expected 81 provinces.");
const byCode = Object.fromEntries(codes.map(code => [code, [...getDistrictsByCityCode(code)].sort((a, b) => a.localeCompare(b, "tr-TR"))]));
const total = Object.values(byCode).reduce((sum, list) => sum + list.length, 0);

const lines = codes.map(code => `  "${code}": ${JSON.stringify(byCode[code])},`);
writeFileSync(new URL("../lib/turkiye-districts.ts", import.meta.url), `// Generated by scripts/generate-turkiye-districts.mjs from PTT's postcode list. Do not edit by hand.
// ${total} districts, keyed by plate code.
export const districtsByPlateCode: Record<string, readonly string[]> = {
${lines.join("\n")}
};
`);
console.log(`Wrote ${codes.length} provinces and ${total} districts.`);
